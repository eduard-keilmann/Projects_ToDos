const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { runBrowserHtml, browserAvailable } = require('./helpers/browser');

test('actual app preserves editing through updates, filtering, saving and data replacement', { skip: !browserAvailable }, async () => {
  const source = fs.readFileSync(path.join(__dirname, '..', 'project_todo_tool.html'), 'utf8');
  const scenario = String.raw`
    const result = document.createElement('output');
    result.id = 'editor-test-result';
    result.textContent = 'NOT RUN';
    document.body.appendChild(result);
    setTimeout(() => { if (result.textContent === 'NOT RUN') { result.textContent = 'FAIL: Incomplete scenario: ' + result.textContent; isDirty = false; } }, 1500);
    (async () => {
      await new Promise(resolve => window.addEventListener('load', resolve, { once: true }));
      try {
        const check = (condition, message) => { if (!condition) throw Error(message); };
        let editable = true;
        let saves = 0;
        isEditingEnabled = () => editable;
        canReviewUnsavedBrowserState = () => !editable;
        scheduleAutosave = () => { saves++; };
        const createdAt = '2026-05-01T00:00:00Z';
        const task = { id: 't', title: '**match**', notes: 'Detail', status: 'open', done: false,
          priority: 'medium', dueDate: '', createdAt };
        state = { projects: [{ id: 'p', name: 'Project', createdAt, tasks: [task] }],
          selectedProjectId: 'p', settings: { theme: 'dark' } };
        render();
        const row = els.taskList.firstElementChild;
        const preview = row.querySelector('.markdown-preview');
        const range = document.createRange();
        range.selectNodeContents(preview.querySelector('strong'));
        const selection = document.getSelection();
        selection.removeAllRanges(); selection.addRange(range);
        renderTasks();
        check(selection.toString() === 'match', 'Preview selection lost');
        check(els.taskList.firstElementChild === row, 'Background refresh replaced row');
        selection.removeAllRanges();
        preview.click();
        const title = row.querySelector('textarea.inline-title-input');
        check(document.activeElement === title, 'Title did not receive focus');
        title.setSelectionRange(2, 4);
        renderTasks();
        check(title.selectionStart === 2 && title.selectionEnd === 4, 'Caret selection lost');
        const status = row.querySelector('.status-select');
        status.focus();
        status.value = 'in-review'; status.dispatchEvent(new Event('change'));
        check(task.status === 'in-review' && !task.done && document.activeElement === status, 'Status transition lost focus or data');
        status.value = 'done'; status.dispatchEvent(new Event('change'));
        check(task.done && els.statDone.textContent === '1', 'Done compatibility/count incorrect');
        status.value = 'open'; status.dispatchEvent(new Event('change'));
        check(!task.done && saves === 3, 'Reverse status transition/save request incorrect');
        let finishSave;
        queueWrite = () => new Promise(resolve => { finishSave = resolve; });
        const saving = persistAndRender();
        status.focus();
        finishSave(); await saving;
        check(status.isConnected && document.activeElement === status, 'Save completion replaced dropdown');
        els.searchInput.value = 'match'; renderTasks();
        preview.click();
        title.value = 'changed'; title.dispatchEvent(new Event('input'));
        check(els.taskList.firstElementChild === row, 'Filter removed active row');
        const notes = row.querySelector('.inline-notes-input');
        notes.focus();
        status.focus();
        notes.focus();
        check(notes.isConnected && document.activeElement === notes, 'Internal focus transfer removed destination');
        els.searchInput.focus();
        check(els.taskList.children.length === 0, 'Deferred filter was not applied');
        check(els.visibleTaskCount.textContent.startsWith('0 visible'), 'Visible count stale');
        els.searchInput.value = ''; renderTasks();
        const newRow = els.taskList.firstElementChild;
        const replacement = { ...state.projects[0], tasks: [{ ...task, title: 'replacement' }] };
        state.projects = [replacement]; render();
        check(els.taskList.firstElementChild !== newRow, 'Imported data reused stale row');
        const second = { ...task, id: 'second', title: 'Second' };
        replacement.tasks.push(second); renderTasks();
        const firstRow = els.taskList.children[0];
        const secondRow = els.taskList.children[1];
        queueWrite = async () => {};
        await applyTaskAction({ projectId: 'p', taskId: 't', type: 'move-down' });
        check(els.taskList.children[0] === secondRow && els.taskList.children[1] === firstRow, 'Reorder replaced rows or failed');
        confirm = () => true;
        queueWrite = () => new Promise(resolve => { finishSave = resolve; });
        const deleting = applyTaskAction({ projectId: 'p', taskId: 't', type: 'delete' });
        const remainingStatus = secondRow.querySelector('.status-select');
        remainingStatus.focus();
        finishSave(); await deleting;
        check(document.activeElement === remainingStatus && secondRow.isConnected, 'Deletion save stole later focus');
        check(replacement.tasks.length === 1 && replacement.tasks[0].id === 'second', 'Deletion changed wrong task');
        editable = false; render();
        check(els.taskList.querySelector('.status-select').disabled, 'Save-failure access did not disable controls');
        const oldStatus = els.taskList.querySelector('.status-select');
        editable = true;
        const other = { ...replacement, id: 'q', tasks: [{ ...second, status: 'open' }] };
        state.projects.push(other); state.selectedProjectId = 'q'; render();
        check(els.taskList.firstElementChild !== secondRow, 'Project switch reused overlapping task ID');
        oldStatus.value = 'done'; oldStatus.dispatchEvent(new Event('change'));
        check(other.tasks[0].status === 'open', 'Detached row edited replacement project');
        state.projects = []; state.selectedProjectId = null; render();
        check(els.taskList.children.length === 0, 'Reset retained task rows');
        result.textContent = 'PASS';
      } catch (error) { result.textContent = 'FAIL: ' + error.message; }
      finally { isDirty = false; }
    })();
  `;
  assert.ok(source.includes('    init();'));
  const output = await runBrowserHtml(source.replace('    init();', scenario));
  assert.equal(output.match(/<output id="editor-test-result">([^<]*)<\/output>/)?.[1], 'PASS');
});
